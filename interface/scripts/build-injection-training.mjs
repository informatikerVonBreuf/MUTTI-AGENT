function windows(text){
  return text.replace(/<!--[^]*?-->/g,' ').split(/\n\s*\n/).map(p=>p.replace(/\s+/g,' ').trim()).filter(p=>p.length>=120&&p.length<=900&&!/^\|/.test(p));
}
const real=[];
for(const company of ['google','amazon']){
  const files=(await fs.readdir(path.join(corpus,company))).filter(f=>f.endsWith('.md')).sort();
  for(const file of files){
    const paragraphs=windows(await fs.readFile(path.join(corpus,company,file),'utf8'));
    const step=Math.max(1,Math.floor(paragraphs.length/12));
    for(let i=0;i<paragraphs.length&&real.length<400;i+=step)real.push(paragraphs[i].slice(0,600));
  }
}
